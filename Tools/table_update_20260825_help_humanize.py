def audit():
    """★ 다시 쓴 글을 <b>같은 자로</b> 재어 본다 — 고쳤다고 말하지 않고 보여준다."""
    bodies = {k: v[2] for k, v in TEXTS.items()}
    alltext = "\n".join(v[1] + "\n" + v[2] for v in TEXTS.values())

    counts = Counter(len(b.split("\n")) for b in bodies.values())
    lens = [len(ln) for b in bodies.values() for ln in b.split("\n") if ln.strip()]
    end_cmd = [k for k, b in bodies.items()
               if re.search(r"(하세요|하십시오|주십시오)\.?$", b.strip())]

    FANCY = ["결", "몫", "층", "이르지", "살필", "셈하", "그이", "저마다", "드러납니다",
             "가라앉", "스러지", "베어", "베고", "베면", "부름"]
    fancy = {w: alltext.count(w) for w in FANCY if alltext.count(w)}

    starts = Counter(ln.strip()[:6] for b in bodies.values()
                     for ln in b.split("\n") if ln.strip())

    BAN = ["넥서스", "몬스터", "유저", "맵 "]
    ban = [(k, w) for k, v in TEXTS.items() for w in BAN if w in v[1] + v[2]]

    print("\n[다시 잰 값]  (괄호는 155절 값)")
    print(f"  본문 줄 수 분포 : {dict(sorted(counts.items()))}   (4:4 · 5:22)")
    print(f"  줄 길이 표준편차 : {statistics.pstdev(lens):.1f}자   (7.0자) · "
          f"최단 {min(lens)} · 최장 {max(lens)}")
    print(f"  «~하세요»로 끝나는 본문 : {len(end_cmd)}/{len(TEXTS)}   (5/26)")
    print(f"  멋 부린 낱말 : {fancy if fancy else '없음'}   (결13 · 드러납니다8 · 층5 · 몫4 …)")
    rep = {k: v for k, v in starts.most_common(5) if v > 1}
    print(f"  되풀이되는 줄머리 : {rep if rep else '없음'}")
    print(f"  금지 어휘 : {ban if ban else '0건 ✓'}")


def main():
    if not os.path.exists(HELP_XLSX):
        raise SystemExit(f"[실패] 도움말 표를 찾지 못했습니다: {HELP_XLSX}")

    shutil.copy2(HELP_XLSX, HELP_XLSX + ".bak")
    wb = openpyxl.load_workbook(HELP_XLSX)

    want = {}
    for hid, (title, summary, body) in TEXTS.items():
        want[f"{hid}_title"] = title
        want[f"{hid}_summary"] = summary
        want[f"{hid}_body"] = body

    ws = wb[KEY_SHEET]
    changed = same = 0
    seen = set()
    for r in range(ROW0, ws.max_row + 1):
        key = str(ws.cell(r, 1).value or "").strip()
        if key not in want:
            continue
        seen.add(key)
        if str(ws.cell(r, 2).value or "") == want[key]:
            same += 1
            continue
        ws.cell(r, 2).value = want[key]
        changed += 1

    st = wb[STEP_SHEET]
    step_changed, step_seen = 0, set()
    for r in range(ROW0, st.max_row + 1):
        hid = str(st.cell(r, 1).value or "").strip()
        order = st.cell(r, 2).value
        if not hid or order is None:
            continue
        k = (hid, int(order))
        if k not in STEPS:
            continue
        step_seen.add(k)
        if str(st.cell(r, 4).value or "") != STEPS[k]:
            st.cell(r, 4).value = STEPS[k]
            step_changed += 1

    try:
        wb.save(HELP_XLSX)
    except PermissionError:
        raise SystemExit(f"[실패] 엑셀에서 열려 있습니다 — 닫고 다시 돌리십시오:\n  {HELP_XLSX}")

    print(f"[휴머나이즈] 문구 {changed}칸 다시 씀 (이미 같던 것 {same}칸) · "
          f"짚어 주기 {step_changed}줄")
    missing = sorted(set(want) - seen)
    if missing:
        print(f"⚠ 표에 없는 키: {', '.join(missing)}")
    step_missing = sorted(set(STEPS) - step_seen)
    if step_missing:
        print(f"⚠ 표에 없는 단계: {step_missing}")

    audit()


if __name__ == "__main__":
    main()
