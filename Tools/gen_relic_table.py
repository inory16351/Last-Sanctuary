HEAD_FILL = PatternFill("solid", fgColor="1F3A56")
HEAD_FONT = Font(color="FFFFFF", bold=True)
KEY_FILL = PatternFill("solid", fgColor="E8EEF5")
SECTION_FONT = Font(bold=True, color="1F3A56")


def write_sheet(ws, headers, keys, types, rows, widths):
    """이 프로젝트의 표 규약 — <b>1행 한글 제목 · 2행 영문 키 · 3행 자료형 · 4행부터 값</b>."""
    for c, v in enumerate(headers, start=1):
        ws.cell(1, c, v).fill = HEAD_FILL
        ws.cell(1, c).font = HEAD_FONT
    for c, v in enumerate(keys, start=1):
        ws.cell(2, c, v).fill = KEY_FILL
    for c, v in enumerate(types, start=1):
        ws.cell(3, c, v)
    for r, row in enumerate(rows, start=4):
        for c, v in enumerate(row, start=1):
            ws.cell(r, c, v)
