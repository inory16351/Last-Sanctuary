    for r in RELICS:
        for slot, name in ((3, "effect_type_01"), (6, "effect_type_02")):
            if r[slot] and r[slot] not in known:
                bad.append("유물 %d: %s '%s' 가 EffectType 에 없습니다" % (r[0], name, r[slot]))
