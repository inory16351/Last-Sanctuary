    KNOWN_SOURCES = {"dig_monster", "dig", "boss", "event"}
    for r in RELICS:
        if r[12] not in KNOWN_SOURCES:
            bad.append("유물 %d: 출처 '%s' 를 모릅니다 (%s 중 하나여야 합니다)"
                       % (r[0], r[12], " · ".join(sorted(KNOWN_SOURCES))))
