def main():
    if not os.path.exists(HELP_XLSX):
        raise SystemExit(f"[실패] 도움말 표를 찾지 못했습니다: {HELP_XLSX}")

    shutil.copy2(HELP_XLSX, HELP_XLSX + ".bak")
    wb = openpyxl.load_workbook(HELP_XLSX)

    # ── StringKeys : 제목 · 요약 · 본문 ──────────────────────────────
    ws = wb[KEY_SHEET]
    want = {}
    for hid, (title, summary, body) in TEXTS.items():
        want[f"{hid}_title"] = title
        want[f"{hid}_summary"] = summary
        want[f"{hid}_body"] = body

    changed, same, seen = 0, 0, set()
    for r in range(ROW0, ws.max_row + 1):
        key = str(ws.cell(r, 1).value or "").strip()
        if key not in want:
            continue
        seen.add(key)
        if str(ws.cell(r, 2).value or "") == want[key]:
            same += 1
            continue
        ws.cell(r, 2).value = want[key]
        changed += 1

    missing = sorted(set(want) - seen)

    # ── HelpStep : 단계 문구 ────────────────────────────────────────
    st = wb[STEP_SHEET]
    step_changed, step_seen = 0, set()
    for r in range(ROW0, st.max_row + 1):
        hid = str(st.cell(r, 1).value or "").strip()
        order = st.cell(r, 2).value
        if not hid or order is None:
            continue
        k = (hid, int(order))
        if k not in STEPS:
            continue
        step_seen.add(k)
        if str(st.cell(r, 4).value or "") != STEPS[k]:
            st.cell(r, 4).value = STEPS[k]
            step_changed += 1

    step_missing = sorted(set(STEPS) - step_seen)

    try:
        wb.save(HELP_XLSX)
    except PermissionError:
        raise SystemExit(f"[실패] 엑셀에서 열려 있습니다 — 닫고 다시 돌리십시오:\n  {HELP_XLSX}")

    print(f"[도움말 어조 개정] 문구 {changed}칸 다시 씀 (이미 같던 것 {same}칸)")
    print(f"                   짚어 주기 {step_changed}줄 다시 씀")
    if missing:
        print(f"⚠ 표에 없는 스트링 키 {len(missing)}개: {', '.join(missing)}")
    if step_missing:
        print(f"⚠ 표에 없는 단계 {len(step_missing)}개: {step_missing}")

    # ── 검산 : 개발 어휘가 남아 있지 않은가 ─────────────────────────
    # ★ 느낌으로 «다 고쳤다» 고 하지 않는다 — 세어서 확인한다(144-5 절의 태도).
    BAN = ["넥서스", "몬스터", "맵 ", "게임이", "유저"]
    hits = []
    for key, text in want.items():
        for w in BAN:
            if w in text:
                hits.append((key, w))
    for k, t in STEPS.items():
        for w in BAN:
            if w in t:
                hits.append((f"{k[0]}#{k[1]}", w))
    print(f"\n[검산] 걷어내기로 한 낱말 {len(hits)}건" + (":" if hits else " — 없습니다 ✓"))
    for key, w in hits:
        print(f"   {key} : «{w}»")


