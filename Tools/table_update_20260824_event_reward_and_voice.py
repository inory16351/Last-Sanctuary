def sec(d):
    return ' (%d초)' % d if d else ''


def frag(rtype, v, d):
    """보상 하나 → result_effect 의 한 토막."""
    v = int(v or 0)
    d = int(d or 0)

    if rtype == 'energy_gain':
        return '에너지 +%d' % v
    if rtype == 'energy_loss':
        return '에너지 %s%d' % (MINUS, v)
    if rtype == 'char_upgrade':
        return '랜덤 천사 1명 능력치 1종 +%d (영구)' % v
    if rtype == 'char_kill_grant':
        return '랜덤 천사 1명 처치 기록 +%d' % v
    if rtype == 'char_join':
        return '천사 1명 합류 (확률 %d%%)' % v
    if rtype == 'char_die':
        return '천사 1명 사망 (확률 %d%%)' % v
    if rtype == 'char_hp_percent_heal':
        return '천사 전체 체력 회복 (최대 체력의 %d%%)' % v
    if rtype == 'char_hp_percent_loss':
        return '천사 전체 체력 %s%d%% (최대 체력 기준)' % (MINUS, v)
    if rtype == 'char_shield_gain':
        return '천사 전체 보호막 (최대 체력의 %d%%, %d초)' % (v, d)
    if rtype == 'char_heal_receive_up':
        return '천사 전체 받는 회복량 +%d%%%s' % (v, sec(d))
    if rtype == 'char_mental_cure':
        return '천사 %d명의 정신 이상 해제' % v
    if rtype in ('char_erosion_up', 'char_erosion_down'):
        s = '+' if rtype.endswith('_up') else MINUS
        return '천사 1명 침식 %s%d' % (s, v)
    if rtype in ('char_all_erosion_up', 'char_all_erosion_down'):
        s = '+' if rtype.endswith('_up') else MINUS
        return '천사 전체 침식 %s%d' % (s, v)
    if rtype == 'enemy_hp_percent_loss':
        return '적 전체 체력 %s%d%% (최대 체력 기준)' % (MINUS, v)
    if rtype == 'enemy_burn':
        return '적 전체 화상 (초당 최대 체력 %d%%, %d초)' % (v, d)
    if rtype == 'enemy_bind':
        return '적 전체 구속 %d초' % d
    if rtype == 'enemy_atk_durat_down':
        return '적 전체 공격력 %s%d%%%s' % (MINUS, v, sec(d))
    if rtype == 'enemy_def_durat_down':
        return '적 전체 방어력 %s%d%%%s' % (MINUS, v, sec(d))
    if rtype == 'summon_enemy':
        return '현재 웨이브 일반 몬스터 %d마리 소환' % v
    if rtype == 'nexus_percent_heal':
        return '성역 체력 +%d%%' % v
    if rtype == 'nexus_percent_loss':
        return '성역 체력 %s%d%%' % (MINUS, v)

    # char_*_durat_up/down · enemy_(atk|move)_spd_durat_up/down
    for prefix, who in (('char_', '천사 전체'), ('enemy_', '적 전체')):
        if not rtype.startswith(prefix) or '_durat_' not in rtype:
            continue
        body = rtype[len(prefix):]
        key = body[:body.index('_durat_')]
        if key not in STAT_NAMES:
            break
        s = '+' if rtype.endswith('_up') else MINUS
        return '%s %s %s%d%%%s' % (who, STAT_NAMES[key], s, v, sec(d))

    raise ValueError('result_effect 문구를 모르는 보상: %s' % rtype)


def effect_line(pairs):
    """«효과 : A · B» 한 줄."""
    parts = [frag(t, v, d) for t, v, d in pairs if t]
    return '효과 : ' + ' · '.join(parts)


