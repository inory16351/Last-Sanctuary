def backup(paths, tag):
    stamp = datetime.datetime.now().strftime('%Y%m%d_%H%M%S')
    dst = os.path.join(BACKUP_ROOT, stamp + '_' + tag)
    os.makedirs(dst, exist_ok=True)
    for p in paths:
        shutil.copy2(p, os.path.join(dst, os.path.basename(p)))
    print('backup:', dst)


def find_col(ws, field, max_col=24):
    """2행이 필드명 줄이다(1행 한글 · 2행 필드 · 3행 타입 · 4행부터 값)."""
    for c in range(1, max_col + 1):
        v = ws.Cells(2, c).Value
        if v is not None and str(v).strip() == field:
            return c
    return 0


def norm(v):
    return '' if v is None else str(v).replace('\r\n', '\n').replace('\r', '\n').strip()


def apply_map(ws, c_key, c_val, table, label):
    """키 열을 훑어 ``table`` 에 있는 행만 고친다. 못 찾은 키는 <b>알린다</b>."""
    last = ws.UsedRange.Rows.Count
    seen, changed = set(), 0
    for r in range(4, last + 1):
        raw = ws.Cells(r, c_key).Value
        if raw is None:
            continue
        try:
            key = int(raw)
        except (TypeError, ValueError):
            continue
        if key not in table:
            continue
        seen.add(key)
        want = table[key]
        if norm(ws.Cells(r, c_val).Value) == want:
            continue
        ws.Cells(r, c_val).Value = want
        changed += 1
    missing = sorted(set(table) - seen)
    if missing:
        print('    ⚠ 표에서 못 찾은 %s: %s' % (label, missing))
    print('    %s %d행 고침 (대상 %d)' % (label, changed, len(table)))
    return changed


def apply_rewards(ws):
    """보상 6칸 + result_effect 를 함께 쓴다 — <b>둘이 갈라지면 안 된다</b>."""
    cols = {}
    for f in ('choice_id', 'result_effect',
              'reward_type_01', 'reward_value_01', 'reward_duration_01',
              'reward_type_02', 'reward_value_02', 'reward_duration_02'):
        cols[f] = find_col(ws, f)
        if cols[f] == 0:
            raise RuntimeError('%s 열을 못 찾았습니다' % f)

    last = ws.UsedRange.Rows.Count
    seen, changed = set(), 0
    for r in range(4, last + 1):
        raw = ws.Cells(r, cols['choice_id']).Value
        if raw is None:
            continue
        try:
            cid = int(raw)
        except (TypeError, ValueError):
            continue
        if cid not in REWARD_CHANGES:
            continue
        seen.add(cid)

        pairs = REWARD_CHANGES[cid]
        for i, (t, v, d) in enumerate(pairs, start=1):
            ws.Cells(r, cols['reward_type_%02d' % i]).Value = t
            ws.Cells(r, cols['reward_value_%02d' % i]).Value = v
            ws.Cells(r, cols['reward_duration_%02d' % i]).Value = d
        line = effect_line(pairs)
        ws.Cells(r, cols['result_effect']).Value = line
        changed += 1
        print('    %d → %s' % (cid, line))

    missing = sorted(set(REWARD_CHANGES) - seen)
    if missing:
        print('    ⚠ 표에서 못 찾은 choice_id: %s' % missing)
    return changed


def audit_effects(ws):
    """
    <b>손대지 않은 줄</b>의 result_effect 가 보상 칸과 맞는지 확인만 한다(고치지 않는다).

    ★ 여기서 «다르다» 가 나오면 문구를 손으로 적어 값과 어긋난 줄이라는 뜻이다 —
      그때는 사람이 보고 정해야 하므로 <b>알리기만</b> 한다.
    """
    cols = {f: find_col(ws, f) for f in
            ('choice_id', 'result_effect',
             'reward_type_01', 'reward_value_01', 'reward_duration_01',
             'reward_type_02', 'reward_value_02', 'reward_duration_02')}
    last = ws.UsedRange.Rows.Count
    bad = 0
    for r in range(4, last + 1):
        raw = ws.Cells(r, cols['choice_id']).Value
        if raw is None:
            continue
        try:
            cid = int(raw)
        except (TypeError, ValueError):
            continue
        pairs = []
        for i in (1, 2):
            t = ws.Cells(r, cols['reward_type_%02d' % i]).Value
            if not t:
                continue
            pairs.append((str(t).strip(),
                          ws.Cells(r, cols['reward_value_%02d' % i]).Value,
                          ws.Cells(r, cols['reward_duration_%02d' % i]).Value))
        if not pairs:
            continue
        want = effect_line(pairs)
        got = norm(ws.Cells(r, cols['result_effect']).Value)
        if got != want:
            bad += 1
            print('    ⚠ %d 문구가 보상과 다릅니다' % cid)
            print('        표 : %s' % got)
            print('        값 : %s' % want)
    print('    문구·값 대조 — 어긋난 줄 %d개' % bad)
    return bad


def main():
    if not os.path.isfile(EVENT_XLSX):
        print('파일이 없습니다:', EVENT_XLSX)
        return 1

    import win32com.client as win32

    # 되살릴 문장에서 «한 다이얼로그 안에서 겹쳤던» 칸을 뺀 뒤, 새로 쓴 칸을 덮는다.
    results = {k: v for k, v in ORIG_RESULT.items() if k not in KEEP_CURRENT}
    results.update(NEW_RESULT)
    choices = dict(ORIG_CHOICE)
    choices.update(NEW_CHOICE)

    backup((EVENT_XLSX,), '이벤트보상다양화_문체복원')

    excel = win32.DispatchEx('Excel.Application')
    excel.Visible = False
    excel.DisplayAlerts = False
    n = 0
    try:
        wb = excel.Workbooks.Open(EVENT_XLSX)

        print('[Event 시트 — 이벤트 대사 되살리기]')
        ws = wb.Worksheets('Event')
        n += apply_map(ws, find_col(ws, 'event_id') or 1,
                       find_col(ws, 'event_script'), ORIG_EVENT, 'event_script')

        print('[ChoiceGroup 시트 — 보상 재배치]')
        ws = wb.Worksheets('ChoiceGroup')
        n += apply_rewards(ws)

        print('[ChoiceGroup 시트 — 선택지·결과 문장]')
        c_cid = find_col(ws, 'choice_id') or 2
        n += apply_map(ws, c_cid, find_col(ws, 'choice_text'), choices, 'choice_text')
        n += apply_map(ws, c_cid, find_col(ws, 'result_script'), results, 'result_script')

        print('[대조 — 문구가 보상과 맞는가]')
        audit_effects(ws)

        if n:
            wb.Save()
        wb.Close(SaveChanges=False)
    finally:
        excel.Quit()

    print()
    print('총 %d칸을 고쳤습니다.' % n)
    print('다음: py -3 Tools/gen_event_assets.py')
    return 0


