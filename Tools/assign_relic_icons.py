def main():
    # ── 자른 그림이 실제로 있는지 먼저 확인 ──
    missing = [k for k in sorted(set(ICONS.values()))
               if not os.path.exists(os.path.join(ICON_DIR, k + '.png'))]
    if missing:
        raise SystemExit('⚠ 잘린 아이콘이 없습니다 (slice_relic_icons.py 를 먼저 돌릴 것):\n  '
                         + '\n  '.join(missing))

    # ── 중복 검사 — 두 유물이 같은 그림을 쓰면 보관함에서 구별이 안 된다 ──
    seen = {}
    dup = []
    for rid, key in ICONS.items():
        if key in seen:
            dup.append('%s ↔ %s : %s' % (seen[key], rid, key))
        seen[key] = rid
    if dup:
        raise SystemExit('⚠ 아이콘이 겹칩니다:\n  ' + '\n  '.join(dup))

    shutil.copyfile(XLSX, BAK)
    print('백업 → %s' % os.path.basename(BAK))

    wb = openpyxl.load_workbook(XLSX)
    ws = wb['Relic']

    col = {}
    for c in range(1, ws.max_column + 1):
        col[str(ws.cell(row=2, column=c).value).strip()] = c

    done = 0
    absent = []
    for r in range(4, ws.max_row + 1):
        rid = ws.cell(row=r, column=col['relic_id']).value
        if not rid:
            continue
        rid = int(rid)
        if rid not in ICONS:
            absent.append(rid)
            continue
        ws.cell(row=r, column=col['icon'], value=ICONS[rid])
        done += 1

    wb.save(XLSX)
    print('아이콘 배정 %d종' % done)
    if absent:
        print('⚠ 배정표에 없는 유물 %d종: %s' % (len(absent), absent))
    print('다음: python Tools/gen_relic_assets.py')


if __name__ == '__main__':
    main()
