def main():
    if not os.path.exists(STRING_XLSX):
        raise SystemExit(f"[실패] 스트링 키 테이블을 찾지 못했습니다: {STRING_XLSX}")

    shutil.copy2(STRING_XLSX, STRING_XLSX + ".bak")
    wb = openpyxl.load_workbook(STRING_XLSX)
    ws = wb[SHEET]

    # string_key → 행
    where = {}
    for r in range(ROW0, ws.max_row + 1):
        k = str(ws.cell(r, 1).value or "").strip()
        if k:
            where[k] = r

    changed, same, missing = 0, 0, []
    for sid, text in sorted(TEXTS.items()):
        key = f"skill_detail_{sid}"
        r = where.get(key)
        if r is None:
            missing.append(key)
            continue
        if str(ws.cell(r, 2).value or "") == text:
            same += 1
            continue
        ws.cell(r, 2).value = text
        changed += 1

    try:
        wb.save(STRING_XLSX)
    except PermissionError:
        raise SystemExit(f"[실패] 엑셀에서 열려 있습니다 — 닫고 다시 돌리십시오:\n  {STRING_XLSX}")

    print(f"[스킬 상세 설명] 다시 쓴 문장 {changed}개 · 이미 같던 것 {same}개")
    if missing:
        print(f"⚠ 스트링 키 테이블에 없는 키 {len(missing)}개: {', '.join(missing)}")
    print("   ⚠ 수치가 없는 스킬 셋(80013 선봉장 · 80023 구원 · 80028 불안정성)은 손대지 않았습니다.")


if __name__ == "__main__":
    main()
